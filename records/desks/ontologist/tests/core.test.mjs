const BOX = process.env.BOX || '/home/user/sgit-ai__website__newsroom__2026__oct__php__box'  // the built box (tools/build.sh --make, then the press's build)
const core = await import(BOX + '/assets/components/sg-graph/v1/v1.0/v1.0.1/sg-graph-core.js')
import { readFileSync } from 'fs'
import assert from 'assert/strict'
const data = JSON.parse(readFileSync(BOX + '/data/graph.json', 'utf8'))
const G = core.load(data)
assert.equal(G.nodes.length, data.nodes.length); assert.equal(G.dropped, 0, 'story graph has no dangling or verbless edges')
const bad = core.load({ nodes: [{ id: 'a' }, { id: 'b' }], edges: [{ from: 'a', to: 'b' }, { from: 'a', to: 'zz', verb: 'cites' }, { from: 'a', to: 'b', rel: 'cites' }] })
assert.equal(bad.edges.length, 1); assert.equal(bad.dropped, 2)
const sub = core.ego(G, 'claim:wikimedia-precaution', 2)
const lay = JSON.stringify([...core.force(G, sub, 800, 600)]); assert.equal(lay, JSON.stringify([...core.force(G, sub, 800, 600)]), 'force layout is deterministic')
assert.equal(JSON.stringify([...core.radial(G, sub, 'claim:wikimedia-precaution', 800, 600)]), JSON.stringify([...core.radial(G, sub, 'claim:wikimedia-precaution', 800, 600)]))
const p = core.path(G, 'party:wiz', 'party:bbc'); assert.ok(p && p.edges.length === 2, 'Wiz to BBC in two steps')
const rows = core.neighbours(G, 'claim:wikimedia-precaution'); assert.ok(rows.some(r => r.phrase === 'relayed by'))
assert.equal(core.safeHref('javascript:alert(1)', 'http://x/'), null); assert.equal(core.safeHref('data:text/html,x', 'http://x/'), null); assert.ok(core.safeHref('../facts/a/index.html', 'http://x/a/b/'))
assert.ok(core.search(G, 'wiz').length > 0)
for (const e of G.edges) assert.ok(G.ontology.verbs[e.verb]?.inverse, 'every verb has an inverse: ' + e.verb)
for (const v of Object.values(G.ontology.verbs)) assert.notEqual(v.label, v.inverse, 'no self-inverse verb')
console.log('core: all assertions passed;', G.nodes.length, 'nodes', G.edges.length, 'edges')
