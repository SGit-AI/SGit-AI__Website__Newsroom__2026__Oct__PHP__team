const { chromium } = require('playwright')
;(async () => { const b = await chromium.launch(), p = await b.newPage({ viewport: { width: 1280, height: 900 } })
  const seen = []; p.on('request', r => { const u = r.url(); if (!u.startsWith('http://localhost') && /telemetry|append\/write|ipapi|ipwho|\.js(\?|$)/.test(u)) seen.push(r.resourceType() + ' ' + u) })
  await p.goto('http://localhost:8790/?page=overview'); await p.waitForSelector('text=Sections of the site')
  const card = p.locator('section.card', { hasText: 'Pages' }).first()
  await card.locator('.hb-row', { hasText: '/sources/calif-php2shell/' }).first().hover()
  await card.locator('.hb-row', { hasText: '/sources/calif-php2shell/' }).first().locator('button.pt').click()
  console.log('tooltip left visible after ◎:', await p.locator('.tip:visible').count())
  await p.locator('iframe.page-frame').scrollIntoViewIfNeeded(); await p.waitForTimeout(6000)
  console.log('script, telemetry or geolocation requests from the framed page:', seen.length ? seen : 'none')
  await p.screenshot({ path: process.argv[2] + '/4-frame.png' }); await b.close() })()
