const { chromium } = require('playwright')
const out = process.argv[2]
;(async () => {
  const b = await chromium.launch(), p = await b.newPage({ viewport: { width: 1280, height: 900 } })
  const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
  await p.goto('http://localhost:8790/'); await p.waitForSelector('text=Drain it into this vault', { timeout: 60000 })
  await p.screenshot({ path: out + '/1-queue.png' })
  await p.click('text=Check the lane again'); await p.waitForTimeout(500)
  await p.screenshot({ path: out + '/2-checking.png' })
  await p.waitForSelector('text=Checked in', { timeout: 30000 }); await p.screenshot({ path: out + '/2b-checked.png' })
  await p.locator('button', { hasText: /^Drain \d/ }).click(); await p.waitForTimeout(2600)
  await p.screenshot({ path: out + '/3-draining.png' })
  await p.waitForSelector('text=Drain 5 event', { timeout: 60000 }); await p.waitForTimeout(300)
  await p.screenshot({ path: out + '/4-done.png' })
  console.log(await p.locator('.log').innerText())
  console.log('steps:\n' + await p.locator('.steps').innerText())
  console.log('errors:', errs)
  await b.close()
})()
